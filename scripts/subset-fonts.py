"""Refresh the unchanged WenKai page font after editing site copy.

Requires fonttools[woff]. Pass the matching LXGW WenKai 1.522 Regular TTF
with --source. Existing WOFF2 files remain as fallbacks for other characters.
The build verifies outlines, widths and line metrics before writing output.
"""

from argparse import ArgumentParser
from html.parser import HTMLParser
from pathlib import Path
import json
import re

from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "assets" / "fonts"


class PageText(HTMLParser):
    def __init__(self):
        super().__init__()
        self.parts = []

    def handle_data(self, data):
        self.parts.append(data)

    def handle_starttag(self, tag, attrs):
        # Include labels, alt text and other potentially displayed attributes.
        self.parts.extend(value for _, value in attrs if value)


def ranges(codes):
    groups = []
    for code in sorted(codes):
        if groups and code == groups[-1][1] + 1:
            groups[-1][1] = code
        else:
            groups.append([code, code])
    return ",".join(
        f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
        for start, end in groups
    )


def face(family, path, codes):
    return (
        f"@font-face{{font-family:'{family}';src:url('assets/fonts/{path}') "
        "format('woff2');font-weight:400;font-style:normal;font-display:swap;"
        f"unicode-range:{ranges(codes)}}}"
    )


def drawing(font, code):
    name = font.getBestCmap()[code]
    glyphs = font.getGlyphSet()
    pen = DecomposingRecordingPen(glyphs)
    glyphs[name].draw(pen)
    return pen.value, font["hmtx"][name]


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path)
    args = parser.parse_args()
    source = TTFont(args.source)
    source.recalcTimestamp = False
    source_map = source.getBestCmap()
    original = TTFont(FONTS / "wenkai-core.woff2")

    page = PageText()
    page.feed((ROOT / "index.html").read_text(encoding="utf-8"))
    text = "".join(page.parts)
    # Raw JS also includes all dynamic labels, template strings and comments.
    # CSS content symbols are collected without the font declaration table.
    for path in sorted(ROOT.glob("*.js")):
        if path.name != "site.js":
            text += path.read_text(encoding="utf-8")
    for path in sorted(ROOT.glob("*.css")):
        if path.name not in ("fonts.css", "site.css"):
            text += path.read_text(encoding="utf-8")
    requested = {ord(char) for char in text}
    # Preserve previous core coverage as well, including spaces/punctuation.
    requested.update(original.getBestCmap())
    requested.update(range(0x20, 0x7F))
    requested.add(0xA0)
    selected = requested & source_map.keys()

    for table, keys in {
        "head": ("unitsPerEm",),
        "hhea": ("ascent", "descent", "lineGap"),
        "OS/2": ("sTypoAscender", "sTypoDescender", "sTypoLineGap",
                 "usWinAscent", "usWinDescent", "fsSelection"),
    }.items():
        for key in keys:
            if getattr(original[table], key) != getattr(source[table], key):
                raise ValueError(f"Source changes line metrics: {table}.{key}")

    verified = set()
    fallback_maps = []
    for path in [FONTS / "wenkai-core.woff2", *sorted(FONTS.glob("wenkai-extra-*.woff2"))]:
        previous = TTFont(path)
        mapping = previous.getBestCmap()
        if "extra" in path.name:
            fallback_maps.append((path.name, set(mapping)))
        for code in set(mapping) & selected:
            if code not in verified:
                if drawing(previous, code) != drawing(source, code):
                    raise ValueError(f"Source changes glyph U+{code:04X}")
                verified.add(code)

    options = subset.Options()
    options.flavor = "woff2"
    options.recalc_timestamp = False
    options.layout_features = ["*"]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=selected)
    subsetter.subset(source)
    source.flavor = "woff2"
    output = FONTS / "wenkai-page.woff2"
    source.save(output)
    result = TTFont(output)
    actual = set(result.getBestCmap())
    if not selected <= actual:
        raise ValueError("Generated font is missing requested characters")

    families = ("Roxane Draft Chinese", "Roxane Chalk Chinese")
    css = ["/* Generated by scripts/subset-fonts.py. Same outlines and metrics; page copy shares one font request. */"]
    css.extend(face(family, output.name, actual) for family in families)
    css.append(face("Roxane Chalk Latin", output.name, set(range(0x30, 0x3A))))
    for name, codes in fallback_maps:
        remaining = codes - actual
        if remaining:
            css.extend(face(family, name, remaining) for family in families)
    css.append("@font-face{font-family:'Roxane Chalk Latin';src:url('assets/fonts/patrick-hand.woff2') format('woff2');font-weight:400;font-style:normal;font-display:swap;unicode-range:U+0000-002F,U+003A-10FFFF}")
    (ROOT / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    print(json.dumps({
        "output": str(output.relative_to(ROOT)),
        "bytes": output.stat().st_size,
        "codepoints": len(actual),
        "matching_existing_glyphs": len(verified),
        "new_characters_over_old_core": len(actual - original.getBestCmap().keys()),
        "missing_supported_characters": len(selected - actual),
        "fallback_overlap": sum(len((codes - actual) & actual) for _, codes in fallback_maps),
    }))


if __name__ == "__main__":
    main()
